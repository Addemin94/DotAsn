// Builds the DotAsn runtime to WebAssembly with NativeAOT-LLVM (native/Asn1.Wasm.csproj) and copies the module
// (lib/dotasn.wasm) and its Emscripten loader (lib/dotasn.js) into the package. Needs the .NET 10 SDK and the
// Emscripten SDK 3.1.56: `emcc` on PATH, $EMSDK, or ../../.cache/emsdk (see README.md).
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const native = join(pkg, 'native');
const repo = resolve(pkg, '../..');

const onPath = (cmd) => {
  try {
    execFileSync(cmd, ['--version'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};

const emsdk = [process.env.EMSDK, join(repo, '.cache/emsdk')].find(d => d && existsSync(join(d, 'emsdk_env.sh')));
if (!onPath('emcc') && !emsdk) {
  console.error('Emscripten not found: install emsdk 3.1.56 (./emsdk install 3.1.56 && ./emsdk activate 3.1.56) and put emcc on PATH or set EMSDK.');
  process.exit(1);
}

const publish = ['dotnet', 'publish', native, '-r', 'browser-wasm', '-c', 'Release', '-p:MSBuildEnableWorkloadResolver=false', '--nologo'];
const quoted = publish.map(a => `'${a.replace(/'/g, "'\\''")}'`).join(' ');
if (onPath('emcc')) {
  execFileSync(publish[0], publish.slice(1), { stdio: 'inherit' });
} else {
  execFileSync('bash', ['-c', `source '${join(emsdk, 'emsdk_env.sh')}' > /dev/null 2>&1 && ${quoted}`], { stdio: 'inherit' });
}

const out = join(native, 'bin/Release/net10.0/browser-wasm/publish');
mkdirSync(join(pkg, 'lib'), { recursive: true });
for (const file of ['dotasn.js', 'dotasn.wasm']) {
  copyFileSync(join(out, file), join(pkg, 'lib', file));
}

// The loader's types (the loader itself is generated by Emscripten).
copyFileSync(join(pkg, 'src/dotasn.d.ts'), join(pkg, 'lib/dotasn.d.ts'));

console.log(`built lib/dotasn.wasm and lib/dotasn.js`);
