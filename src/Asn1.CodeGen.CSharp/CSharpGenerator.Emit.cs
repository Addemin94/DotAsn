namespace Asn1.CodeGen.CSharp;

/// <summary>Emission: every generated declaration is a Roslyn syntax node, formatted by <see cref="SourceFormatter"/>.</summary>
public sealed partial class CSharpGenerator
{
    private AttributeListSyntax GeneratedCode => Cs.Attribute(Global("System.CodeDom.Compiler.GeneratedCode"), Str("DotAsn"), Str(Version));

    private static NameSyntax Equality => Runtime("Asn1ValueEquality");

    private ImmutableArray<GeneratedFile> Emit()
    {
        var files = new List<GeneratedFile>();
        foreach (var ctx in _modules)
        {
            var module = Naming.Pascal(ctx.Module.Name);
            if (_options.Layout == OutputLayout.FilePerModule)
            {
                var members = ctx.TopTypes.SelectMany(EmitType).Concat(EmitAliases(ctx)).Append(EmitModuleClass(ctx));
                files.Add(new GeneratedFile(module + ".g.cs", Unit(ctx, members)));
            }
            else
            {
                foreach (var t in ctx.TopTypes)
                {
                    files.Add(new GeneratedFile($"{module}/{t.Name}.g.cs", Unit(ctx, EmitType(t))));
                }

                files.Add(new GeneratedFile($"{module}/{ctx.ClassName}.g.cs", Unit(ctx, EmitAliases(ctx).Append(EmitModuleClass(ctx)))));
            }
        }

        return [.. files];
    }

    /// <summary>A compilation unit: the auto-generated header, nullable context, a file-scoped namespace and the members.</summary>
    private string Unit(ModuleContext ctx, IEnumerable<MemberDeclarationSyntax> members)
    {
        var header = TriviaList(
            Comment("// <auto-generated>"),
            EndOfLine("\n"),
            Comment($"//     Generated by DotAsn {Version} from ASN.1 module {ctx.Module.Name}."),
            EndOfLine("\n"),
            Comment("//     Do not edit: changes are lost when the code is regenerated. Extend the partial types instead."),
            EndOfLine("\n"),
            Comment("// </auto-generated>"),
            EndOfLine("\n"),
            Trivia(NullableDirectiveTrivia(Token(SyntaxKind.EnableKeyword), true)),
            Trivia(PragmaWarningDirectiveTrivia(Token(SyntaxKind.DisableKeyword), SeparatedList<ExpressionSyntax>(new[] { "CS1591", "CS0108", "CS8618" }.Select(IdentifierName)), true)),
            EndOfLine("\n"));
        var ns = FileScopedNamespaceDeclaration(NamespaceName(ctx.Namespace))
            .WithNamespaceKeyword(Token(header, SyntaxKind.NamespaceKeyword, TriviaList()))
            .WithMembers(List(members));
        return SourceFormatter.Format(CompilationUnit().WithMembers(SingletonList<MemberDeclarationSyntax>(ns)));
    }

    private static NameSyntax NamespaceName(string dotted)
    {
        var parts = dotted.Split('.');
        NameSyntax name = IdentifierName(parts[0]);
        foreach (var p in parts.Skip(1))
        {
            name = QualifiedName(name, IdentifierName(p));
        }

        return name;
    }

    /// <summary>Attaches documentation when <see cref="CSharpGeneratorOptions.GenerateDocumentation"/> is set.</summary>
    private T Doc<T>(T node, string? summary, string? remarks = null)
        where T : SyntaxNode => _options.GenerateDocumentation ? node.WithDoc(summary, remarks) : node;

    private static string Notation(AsnType t)
    {
        var name = t.IsReference ? t.Reference?.Name ?? t.DisplayName : AsnType.KindName(t.Kind, t.StringKind);
        var constraints = string.Concat((t.IsReference ? t.OwnConstraints : t.Constraints).Select(c => " " + c));
        return name + constraints;
    }

    private static string Display(TypeSyntax type) => type.NormalizeWhitespace().ToString().Replace("global::", string.Empty, StringComparison.Ordinal);

    // ------------------------------------------------------------------ types

    private IEnumerable<MemberDeclarationSyntax> EmitType(GenType t) => t.Kind switch
    {
        GenKind.Enum => EmitEnum(t),
        GenKind.Choice => [EmitChoice(t)],
        _ => [EmitSequence(t)],
    };

    private string TypeDoc(GenType t) => t.Assignment?.Documentation ?? t.Definition.Documentation ?? string.Empty;

    /// <summary>Base types of a generated value class: <c>IAsn1Value&lt;T&gt;</c> and <c>IEquatable&lt;T&gt;</c>.</summary>
    private static BaseListSyntax ValueBases(TypeSyntax self) => Bases(Runtime("IAsn1Value", self), Global("System.IEquatable", self));

    /// <summary><c>public override bool Equals(object? obj) =&gt; Equals(obj as T);</c></summary>
    private static MethodDeclarationSyntax EqualsObject(TypeSyntax self) =>
        ArrowMethod(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.OverrideKeyword), BoolType, "Equals", [Param(Nullable(ObjectType), "obj")],
            Call(Id("Equals"), BinaryExpression(SyntaxKind.AsExpression, Id("obj"), self)));

    /// <summary><c>public override string ToString() =&gt; Asn1ValueFormatter.Format(Asn1Type, this);</c></summary>
    private static MethodDeclarationSyntax ToStringMethod() =>
        ArrowMethod(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.OverrideKeyword), StringType, "ToString", [],
            Call(Member(Runtime("Asn1ValueFormatter"), "Format"), Id("Asn1Type"), ThisExpression()));

    private PropertyDeclarationSyntax DescriptorProperty(TypeSyntax self, ExpressionSyntax creation) =>
        Doc(ArrowProperty(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword), Runtime("Asn1Type", self), "Asn1Type", FieldOrInit(creation)),
            "The ASN.1 type descriptor used by all encoding rules.");

    private ClassDeclarationSyntax EmitSequence(GenType t)
    {
        var def = t.Definition;
        var self = Id(t.Name);
        var members = new List<MemberDeclarationSyntax>();
        foreach (var c in def.Components)
        {
            var prop = t.Members[c];
            var clr = Clr(c.Type);
            var notation = $"{c.Name} {Notation(c.Type)}" + c.Presence switch
            {
                Presence.Optional => " OPTIONAL",
                Presence.Default => " DEFAULT " + c.DefaultValue,
                _ => string.Empty,
            } + (c.IsExtensionAddition ? " (extension addition)" : string.Empty);
            var publicOnly = Modifiers(SyntaxKind.PublicKeyword);
            PropertyDeclarationSyntax property;
            if (DefaultExpr(c) is { } dvExpr)
            {
                property = AutoProperty(publicOnly, clr, prop, settable: true, dvExpr);
            }
            else if (c.IsOptional || c.IsExtensionAddition)
            {
                property = AutoProperty(publicOnly, Nullable(clr), prop, settable: true);
            }
            else
            {
                property = AutoProperty(publicOnly, clr, prop, settable: true, IsValueType(c.Type) ? null : MandatoryInitializer(c.Type));
            }

            members.Add(Doc(property, c.Documentation, notation));
        }

        members.Add(DescriptorProperty(self, New(
            Runtime("SequenceType", self),
            Str(t.AsnName),
            Bool(def.Kind == TypeKind.Set),
            Lambda(New(self)),
            Lambda(Collection(def.Components.Select(c => ComponentExpr(t, c)))),
            Bool(def.IsExtensible),
            TagsOf(def),
            ConstraintList(def.Constraints))));

        // Equality and formatting.
        var equal = IsNotNull(Id("other"));
        foreach (var c in def.Components)
        {
            equal = And(equal, Call(Member(Equality, "Equal"), Id(t.Members[c]), Member(Id("other"), t.Members[c])));
        }

        members.Add(Doc(ArrowMethod(Modifiers(SyntaxKind.PublicKeyword), BoolType, "Equals", [Param(Nullable(self), "other")], equal), "Structural equality over all components."));
        members.Add(EqualsObject(self));

        var statements = new List<StatementSyntax>
        {
            LocalDeclarationStatement(VariableDeclaration(IdentifierName("var")).AddVariables(
                VariableDeclarator("hash").WithInitializer(EqualsValueClause(New(Global("System.HashCode")))))),
        };
        statements.AddRange(def.Components.Select(c => (StatementSyntax)ExpressionStatement(
            Call(Member(Id("hash"), "Add"), Call(Member(Equality, "Hash"), Id(t.Members[c]))))));
        statements.Add(ReturnStatement(Call(Member(Id("hash"), "ToHashCode"))));
        members.Add(MethodDeclaration(IntType, "GetHashCode").WithModifiers(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.OverrideKeyword)).WithBody(Block(statements)));
        members.Add(ToStringMethod());
        members.AddRange(t.Nested.SelectMany(EmitType));

        var declaration = ClassDeclaration(t.Name)
            .WithAttributeLists(SingletonList(GeneratedCode))
            .WithModifiers(Modifiers(Access, SyntaxKind.SealedKeyword, SyntaxKind.PartialKeyword))
            .WithBaseList(ValueBases(self))
            .WithMembers(List(members));
        return Doc(declaration, TypeDoc(t), $"ASN.1: {t.AsnName} ::= {AsnType.KindName(def.Kind)}{(def.IsExtensible ? " (extensible)" : string.Empty)}");
    }

    /// <summary>The <c>SequenceComponent</c> creation for one component.</summary>
    private ExpressionSyntax ComponentExpr(GenType t, AsnComponent c)
    {
        var prop = t.Members[c];
        var clr = Clr(c.Type);
        var nullable = (c.IsOptional && c.Presence != Presence.Default) || (c.IsExtensionAddition && c.Presence != Presence.Default);
        var defaultExpr = DefaultExpr(c);
        if (c.Presence == Presence.Default && defaultExpr is null)
        {
            nullable = true;
        }

        var field = Member(Id("o"), prop);
        var get = nullable
            ? IsValueType(c.Type) ? Lambda(Call(Member(field, "GetValueOrDefault")), "o") : Lambda(NotNull(field), "o")
            : Lambda(field, "o");
        var presence = c.Presence switch
        {
            Presence.Optional => "Optional",
            Presence.Default when defaultExpr is not null => "Default",
            Presence.Default => "Optional",
            _ => "Required",
        };
        return New(Runtime("SequenceComponent", Id(t.Name), clr), new[]
        {
            Argument(Str(c.Name)),
            Argument(Lambda(Desc(c.Type))),
            Argument(get),
            Argument(Lambda(Assign(field, Id("v")), "o", "v")),
            Argument(Member(Runtime("Asn1Presence"), presence)),
            Named("isPresent", nullable ? Lambda(IsNotNull(field), "o") : Null),
            Named("isDefault", defaultExpr is not null ? Lambda(Call(Member(Equality, "Equal"), field, defaultExpr), "o") : Null),
            Named("applyDefault", Null),
            Named("extensionAdditionIndex", Int32(c.ExtensionAdditionIndex)),
            Named("isInRootPart2", Bool(c.IsInRootPart2)),
            Named("isInExtensionGroup", Bool(c.IsInExtensionGroup)),
        });
    }

    private ClassDeclarationSyntax EmitChoice(GenType t)
    {
        var def = t.Definition;
        var self = Id(t.Name);
        var kindType = Id("AlternativeKind");
        var publicOverride = Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.OverrideKeyword);
        var members = new List<MemberDeclarationSyntax>
        {
            ConstructorDeclaration(t.Name).WithModifiers(Modifiers(SyntaxKind.PrivateKeyword, SyntaxKind.ProtectedKeyword)).WithBody(Block()),
        };

        var kinds = new List<EnumMemberDeclarationSyntax>();
        if (def.IsExtensible)
        {
            kinds.Add(Doc(EnumMemberDeclaration("UnknownExtension").WithEqualsValue(EqualsValueClause(Int32(-1))), "An extension alternative unknown to this version."));
        }

        kinds.AddRange(def.Components.Select((c, i) => EnumMemberDeclaration(t.Members[c]).WithEqualsValue(EqualsValueClause(Int32(i)))));
        members.Add(Doc(EnumDeclaration("AlternativeKind").WithModifiers(Modifiers(SyntaxKind.PublicKeyword)).WithMembers(SeparatedList(kinds)), "Identifies the chosen alternative."));
        members.Add(Doc(PropertyDeclaration(kindType, "Kind").WithModifiers(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.AbstractKeyword)).WithAccessorList(Accessors(settable: false)), "The chosen alternative."));
        members.Add(AbstractMethod(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.AbstractKeyword), BoolType, "Equals", [Param(Nullable(self), "other")]));
        members.Add(EqualsObject(self));
        members.Add(AbstractMethod(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.AbstractKeyword, SyntaxKind.OverrideKeyword), IntType, "GetHashCode", []));
        members.Add(ToStringMethod());

        var unknown = Id("UnknownExtension");
        members.Add(DescriptorProperty(self, New(
            Runtime("ChoiceType", self),
            Str(t.AsnName),
            Lambda(Collection(def.Components.Select(c => (ExpressionSyntax)New(
                Runtime("ChoiceAlternative", self, Clr(c.Type)),
                Str(c.Name),
                Lambda(Desc(c.Type)),
                Lambda(Member(Paren(Cast(Id(t.Members[c]), Id("c"))), "Value"), "c"),
                Lambda(New(Id(t.Members[c]), Id("v")), "v"),
                Int32(c.ExtensionAdditionIndex),
                Bool(c.IsInExtensionGroup))))),
            Lambda(Cast(IntType, Member(Id("c"), "Kind")), "c"),
            Bool(def.IsExtensible),
            def.IsExtensible ? Lambda(New(unknown, Id("index"), Id("raw")), "index", "raw") : Null,
            def.IsExtensible
                ? Lambda(ConditionalExpression(
                    IsType(Id("c"), unknown, "u"),
                    TupleExpression(SeparatedList(new[] { Argument(Member(Id("u"), "Index")), Argument(Member(Id("u"), "Raw")) })),
                    Null), "c")
                : Null,
            TagsOf(def),
            ConstraintList(def.Constraints))));

        foreach (var c in def.Components)
        {
            var alt = t.Members[c];
            var clr = Clr(c.Type);
            var alternative = ClassDeclaration(alt)
                .WithModifiers(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.SealedKeyword, SyntaxKind.PartialKeyword))
                .WithBaseList(Bases(self))
                .WithMembers(List<MemberDeclarationSyntax>(
                [
                    Doc(ConstructorDeclaration(alt).WithModifiers(Modifiers(SyntaxKind.PublicKeyword))
                        .WithParameterList(ParameterList(SingletonSeparatedList(Param(clr, "value"))))
                        .WithExpressionBody(ArrowExpressionClause(Assign(Id("Value"), Id("value"))))
                        .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)), "Creates the alternative."),
                    Doc(AutoProperty(Modifiers(SyntaxKind.PublicKeyword), clr, "Value", settable: true), "The alternative's value."),
                    ArrowProperty(publicOverride, kindType, "Kind", Member(kindType, alt)),
                    ArrowMethod(publicOverride, BoolType, "Equals", [Param(Nullable(self), "other")],
                        And(IsType(Id("other"), Id(alt), "o"), Call(Member(Equality, "Equal"), Id("Value"), Member(Id("o"), "Value")))),
                    ArrowMethod(publicOverride, IntType, "GetHashCode", [],
                        Call(Member(Global("System.HashCode"), "Combine"), Cast(IntType, Id("Kind")), Call(Member(Equality, "Hash"), Id("Value")))),
                ]));
            members.Add(Doc(alternative, c.Documentation, $"{c.Name} {Notation(c.Type)}{(c.IsExtensionAddition ? " (extension addition)" : string.Empty)}"));
        }

        if (def.IsExtensible)
        {
            var raw = Runtime("Asn1OpenValue");
            var span = (ExpressionSyntax target) => Member(Member(target, "Encoded"), "Span");
            members.Add(Doc(ClassDeclaration("UnknownExtension")
                .WithModifiers(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.SealedKeyword, SyntaxKind.PartialKeyword))
                .WithBaseList(Bases(self))
                .WithMembers(List<MemberDeclarationSyntax>(
                [
                    Doc(ConstructorDeclaration("UnknownExtension").WithModifiers(Modifiers(SyntaxKind.PublicKeyword))
                        .WithParameterList(ParameterList(SeparatedList([Param(IntType, "index"), Param(raw, "raw")])))
                        .WithBody(Block(ExpressionStatement(Assign(Id("Index"), Id("index"))), ExpressionStatement(Assign(Id("Raw"), Id("raw"))))), "Creates the value."),
                    Doc(AutoProperty(Modifiers(SyntaxKind.PublicKeyword), IntType, "Index", settable: false), "The extension index (PER), or -1 when the encoding rule has no index (BER)."),
                    Doc(AutoProperty(Modifiers(SyntaxKind.PublicKeyword), raw, "Raw", settable: false), "The raw encoding."),
                    ArrowProperty(publicOverride, kindType, "Kind", Member(kindType, "UnknownExtension")),
                    ArrowMethod(publicOverride, BoolType, "Equals", [Param(Nullable(self), "other")],
                        And(IsType(Id("other"), unknown, "o"), Call(Member(Global("System.MemoryExtensions"), "SequenceEqual"), span(Id("Raw")), span(Member(Id("o"), "Raw"))))),
                    ArrowMethod(publicOverride, IntType, "GetHashCode", [], Member(Member(Id("Raw"), "Encoded"), "Length")),
                ])), "An extension alternative from a later version, kept as its raw encoding."));
        }

        members.AddRange(t.Nested.SelectMany(EmitType));
        var declaration = ClassDeclaration(t.Name)
            .WithAttributeLists(SingletonList(GeneratedCode))
            .WithModifiers(Modifiers(Access, SyntaxKind.AbstractKeyword, SyntaxKind.PartialKeyword))
            .WithBaseList(ValueBases(self))
            .WithMembers(List(members));
        return Doc(declaration, TypeDoc(t), $"ASN.1: {t.AsnName} ::= CHOICE{(def.IsExtensible ? " (extensible)" : string.Empty)}. Use the nested classes to create values.");
    }

    // Enumerations with values beyond 64 bits are rejected as unsupported before emission, so every item fits.
    // int.MinValue is taken by Asn1UnknownExtension.
    private static string EnumUnderlying(GenType t) =>
        t.Definition.EnumItems.All(i => Fits(i.Value, "int") && i.Value != int.MinValue) ? "int" : "long";

    private IEnumerable<MemberDeclarationSyntax> EmitEnum(GenType t)
    {
        var def = t.Definition;
        var underlying = EnumUnderlying(t);
        var items = def.EnumItems.Select(item => Doc(
            EnumMemberDeclaration(t.EnumMembers[item.Name]).WithEqualsValue(EqualsValueClause(Integer(item.Value, underlying))),
            item.Documentation,
            item.IsExtension ? $"{item.Name}({item.Value}), extension addition" : $"{item.Name}({item.Value})")).ToList();
        if (def.IsExtensible)
        {
            items.Add(Doc(
                EnumMemberDeclaration("Asn1UnknownExtension").WithEqualsValue(EqualsValueClause(Member(IntegerType(underlying), "MinValue"))),
                "An item from a later version of the enumeration (decoding only; cannot be encoded)."));
        }

        yield return Doc(
            EnumDeclaration(t.Name)
                .WithAttributeLists(SingletonList(GeneratedCode))
                .WithModifiers(Modifiers(Access))
                .WithBaseList(Bases(IntegerType(underlying)))
                .WithMembers(SeparatedList(items)),
            TypeDoc(t),
            $"ASN.1: {t.AsnName} ::= ENUMERATED{(def.IsExtensible ? " (extensible)" : string.Empty)}");

        if (t.Parent is null)
        {
            // A C# 14 extension block exposes the descriptor as E.Asn1Type, like the generated classes.
            var extension = ExtensionBlockDeclaration()
                .WithParameterList(ParameterList(SingletonSeparatedList(Parameter(Identifier(string.Empty)).WithType(Id(t.Name)))))
                .WithOpenBraceToken(Token(SyntaxKind.OpenBraceToken))
                .WithMembers(SingletonList<MemberDeclarationSyntax>(Doc(
                    ArrowProperty(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword), Runtime("Asn1Type", Id(t.Name)), "Asn1Type", t.DescriptorExpression),
                    "The ASN.1 type descriptor.")))
                .WithCloseBraceToken(Token(SyntaxKind.CloseBraceToken));
            yield return Doc(
                ClassDeclaration(t.Name + "Asn1Extensions")
                    .WithAttributeLists(SingletonList(GeneratedCode))
                    .WithModifiers(Modifiers(Access, SyntaxKind.StaticKeyword))
                    .WithMembers(SingletonList<MemberDeclarationSyntax>(extension)),
                $"Exposes the ASN.1 descriptor of {t.Name} as {t.Name}.Asn1Type.");
        }
    }

    private ExpressionSyntax EnumDescriptor(GenType t)
    {
        var def = t.Definition;
        var items = def.EnumItems.Select(i => (ExpressionSyntax)TupleExpression(SeparatedList(new[] { Argument(Str(i.Name)), Argument(Int64((long)i.Value)), Argument(Bool(i.IsExtension)) })));
        return New(
            Runtime("EnumeratedType", t.TypeName),
            Str(t.AsnName),
            New(Runtime("EnumerationInfo"), Collection(items), Bool(def.IsExtensible)),
            Lambda(Cast(LongType, Id("v")), "v"),
            Lambda(Cast(t.TypeName, Id("v")), "v"),
            def.IsExtensible ? Lambda(Member(t.TypeName, "Asn1UnknownExtension"), "_") : Null,
            TagsOf(def),
            ConstraintList(def.Constraints));
    }

    // ------------------------------------------------------------------ aliases and the module class

    private IEnumerable<MemberDeclarationSyntax> EmitAliases(ModuleContext ctx)
    {
        foreach (var (ta, property, alias) in ctx.Assignments)
        {
            if (alias is null)
            {
                continue;
            }

            var type = ta.Type!;
            var clr = Clr(type);
            var members = new List<MemberDeclarationSyntax>
            {
                Doc(ArrowProperty(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword), Runtime("Asn1Type", clr), "Asn1Type", Member(ctx.ClassTypeName, property)), "The ASN.1 type descriptor."),
            };
            var def = type.Definition;

            // A member may not have the name of its class (CS0542) or of the Asn1Type property. Hiding an inherited
            // member is allowed (CS0108 is disabled in generated files), as in the other generated classes.
            var scope = new NameScope([alias, "Asn1Type"]);
            string MemberName(NamedNumber n)
            {
                var memberName = scope.Allocate(Naming.Pascal(n.Name));
                ReportRename(n.Name, memberName, n.Location, "member of " + alias);
                return memberName;
            }

            if (IntegerKeyword(type) is not null)
            {
                // X.680 19.5 allows named numbers outside the constraint; those get a type that holds them.
                var keyword = FixedConstantKeyword(type);
                members.AddRange(def.NamedNumbers.Select(n => Doc(IntegerConstant(MemberName(n), n.Value, keyword), n.Documentation, $"{n.Name}({n.Value})")));
            }
            else if (def.Kind == TypeKind.BitString)
            {
                members.AddRange(def.NamedNumbers.Select(n => Doc(
                    IntegerConstant(MemberName(n), n.Value, fixedKeyword: null),
                    n.Documentation ?? $"Position of the named bit '{n.Name}'.",
                    $"{n.Name}({n.Value})")));
            }

            yield return Doc(
                ClassDeclaration(alias)
                    .WithAttributeLists(SingletonList(GeneratedCode))
                    .WithModifiers(Modifiers(Access, SyntaxKind.StaticKeyword, SyntaxKind.PartialKeyword))
                    .WithMembers(List(members)),
                ta.Documentation,
                $"ASN.1: {ta.QualifiedName} ::= {Notation(type)}. Values are represented as {Display(clr)}.");
        }
    }

    private ClassDeclarationSyntax EmitModuleClass(ModuleContext ctx)
    {
        var publicStatic = Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword);
        var members = new List<MemberDeclarationSyntax>();
        foreach (var (ta, property, _) in ctx.Assignments)
        {
            var type = ta.Type!;
            var descriptorType = Runtime("Asn1Type", Clr(type));
            ExpressionSyntax body;
            if (_types.TryGetValue(type.Definition, out var gt) && gt.Assignment == ta)
            {
                body = gt.Kind == GenKind.Enum ? FieldOrInit(EnumDescriptor(gt)) : Member(gt.TypeName, "Asn1Type");
            }
            else if (type.Definition.Assignment != ta)
            {
                // An alias of another assignment (A ::= B): the descriptor carries the alias's own name, which XER uses
                // as the XML element name (X.680 14.2, X.693 8.3.1).
                body = FieldOrInit(Call(Member(Desc(type), "WithConstraints"), EmptyCollection, Str(ta.QualifiedName)));
            }
            else
            {
                body = FieldOrInit(Desc(type));
            }

            members.Add(Doc(ArrowProperty(publicStatic, descriptorType, property, body), $"Descriptor of {ta.QualifiedName}."));
        }

        foreach (var e in ctx.NestedEnums)
        {
            members.Add(Doc(
                ArrowProperty(publicStatic, Runtime("Asn1Type", e.TypeName), e.EnumDescriptorProperty!, FieldOrInit(EnumDescriptor(e))),
                $"Descriptor of the nested enumeration {e.DisplayName}."));
        }

        foreach (var (va, name) in ctx.Values)
        {
            if (EmitValue(va, name) is { } member)
            {
                members.Add(Doc(member, va.Documentation, $"ASN.1: {va.Name} {Notation(va.Type!)} ::= {va.Value}"));
            }
        }

        return Doc(
            ClassDeclaration(ctx.ClassName)
                .WithAttributeLists(SingletonList(GeneratedCode))
                .WithModifiers(Modifiers(Access, SyntaxKind.StaticKeyword, SyntaxKind.PartialKeyword))
                .WithMembers(List(members)),
            $"Descriptors and values of ASN.1 module {ctx.Module.Name}.",
            ctx.Module.Oid is null ? null : $"Module object identifier {ctx.Module.Oid}.");
    }

    /// <summary>
    /// The CLR keyword that constants of an INTEGER type (named numbers, value assignments) must have: the C# type of a
    /// bounded type of at most 64 bits; null when constants are typed by their value instead (unbounded or extensible
    /// types under every <see cref="IntegerMapping"/>, and types wider than 64 bits).
    /// </summary>
    private string? FixedConstantKeyword(AsnType type) =>
        IntegerInfo(IntegerDefinition(type)) is { Bounded: true, Keyword: not "BigInteger" and var keyword } ? keyword : null;

    /// <summary>
    /// The CLR type of an integer constant: <paramref name="fixedKeyword"/> when given and the value fits it, otherwise
    /// int, long or ulong by value (BigInteger beyond 64 bits), so that constants stay compile-time constants.
    /// </summary>
    private static string ConstantType(BigInteger value, string? fixedKeyword) =>
        fixedKeyword is not null && Fits(value, fixedKeyword) ? fixedKeyword : ConstantKeyword(value);

    /// <summary>A constant (a static read-only field beyond 64 bits) holding an integer; see <see cref="ConstantType"/>.</summary>
    private static FieldDeclarationSyntax IntegerConstant(string name, BigInteger value, string? fixedKeyword)
    {
        var type = ConstantType(value, fixedKeyword);
        return type == "BigInteger"
            ? Field(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword, SyntaxKind.ReadOnlyKeyword), BigIntegerType, name, Big(value))
            : Field(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.ConstKeyword), IntegerType(type), name, Integer(value, type));
    }

    /// <summary>
    /// The expression of a component's DEFAULT value, computed once per component. A DEFAULT that cannot be expressed
    /// (e.g. outside its C# type) makes the component OPTIONAL in the generated code.
    /// </summary>
    private ExpressionSyntax? DefaultExpr(AsnComponent c)
    {
        if (c.Presence != Presence.Default || c.DefaultValue is not { } dv)
        {
            return null;
        }

        if (!_defaults.TryGetValue(c, out var expr))
        {
            expr = ValueExpr(dv, c.Type, out var outside);
            if (outside is var (value, type))
            {
                ReportValueOutsideType(value, type, $"the DEFAULT of '{c.Name}' is generated as OPTIONAL");
            }

            _defaults[c] = expr;
        }

        return expr;
    }

    /// <summary>A constant, read-only field or property for a value assignment, or null if the value cannot be expressed.</summary>
    private MemberDeclarationSyntax? EmitValue(ValueAssignmentSymbol va, string name)
    {
        var value = va.Value!;
        var type = va.Type!;
        var publicConst = Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.ConstKeyword);
        switch (value)
        {
            case IntegerValue i when type.Kind == TypeKind.Integer:
                {
                    // The CLR type of the value's ASN.1 type (e.g. byte for INTEGER (0..255)).
                    // Reported when the constant cannot have the C# type of its INTEGER type: a bounded type the value
                    // violates, or an unbounded type mapped to long (IntegerMapping.Int64) for a value beyond long.
                    var keyword = FixedConstantKeyword(type);
                    var propertyType = IntegerKeyword(type)!;
                    if (keyword is not null ? !Fits(i.Value, keyword) : !Fits(i.Value, propertyType))
                    {
                        ReportValueOutsideType(i, type, $"'{va.Name}' is generated as {ConstantType(i.Value, keyword)}");
                    }

                    return IntegerConstant(name, i.Value, keyword);
                }
            case BooleanValue b:
                return Field(publicConst, BoolType, name, Bool(b.Value));
            case StringValue s:
                return Field(publicConst, StringType, name, Str(s.Value));
            case RealValue r when double.IsFinite(r.Value) && !(r.Value == 0 && double.IsNegative(r.Value)):
                return Field(publicConst, DoubleType, name, Float64(r.Value));
            case EnumeratedValue when _types.ContainsKey(type.Definition):
                return Field(publicConst, Clr(type), name, ValueExpr(value, type)!);
        }

        if (ValueExpr(value, type, out var outsideType) is not { } expr)
        {
            if (outsideType is var (outside, ofType))
            {
                ReportValueOutsideType(outside, ofType, $"'{va.Name}' is not generated");
            }
            else
            {
                _diagnostics.Add(Diagnostic.Create(DiagnosticCatalog.GenerationUnsupported, va.Location, va.Name, "the value notation cannot be represented in C#"));
            }

            return null;
        }

        // Mutable values are created on each access so callers cannot change shared state.
        var immutable = value is ObjectIdentifierValue or RelativeOidValue or BitStringValue or RealValue or NullValue;
        return immutable
            ? Field(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword, SyntaxKind.ReadOnlyKeyword), Clr(type), name, expr)
            : ArrowProperty(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.StaticKeyword), Clr(type), name, expr);
    }
